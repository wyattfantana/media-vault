    echo "STEP 5: Download Subtitles"
    echo "════════════════════════════════════════════════════════"
    echo "→ http://localhost:6767/series"
    echo ""
    echo "  • Click on Law & Order SVU"
    echo "  • Tools → Search All Episodes"
    echo "  • Wait 10-30 minutes for all subtitles"
    echo ""

    echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
    echo ""
    echo "💡 TIP: You can disable/ignore Sonarr after this!"
    echo "   Once Bazarr knows about the series, it will keep"
    echo "   managing subtitles even if Sonarr is stopped."
    echo ""
else
    echo "   ❌ Failed to start Sonarr"
    echo "   Try: docker compose -f docker-compose-sonarr.yml up -d"
fi
