#!/bin/bash
# Minimal Sonarr setup - ONLY for Bazarr subtitle integration

echo "🎯 Setting up minimal Sonarr for Bazarr subtitle management"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
